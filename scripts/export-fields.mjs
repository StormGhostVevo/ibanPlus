// Writes docs/fields.json and docs/FIELDS.md from the built library. Run after `npm run build`.
import { writeFileSync } from 'node:fs';
import { getConfiguredCountries, getCountryConfig, FALLBACK_CONFIG } from '../dist/index.js';

const plain = (f) => ({
  key: f.key,
  label: f.label,
  helpText: f.helpText,
  placeholder: f.placeholder,
  required: f.required,
  requiredUnless: f.requiredUnless ?? [],
  pattern: f.pattern ? f.pattern.source : null,
  validate: f.validate ?? null,
  errorMessage: f.errorMessage,
  normalise: f.normalise,
  inputMode: f.inputMode,
  maxLength: f.maxLength,
  options: f.options ?? null,
  sensitive: f.sensitive,
});

const codes = getConfiguredCountries();
const countries = {};
for (const code of codes) {
  const c = getCountryConfig(code);
  countries[code] = { name: c.name, xeroSyncable: c.xeroSyncable, fields: c.fields.map(plain) };
}
const fallback = { name: FALLBACK_CONFIG.name, fields: FALLBACK_CONFIG.fields.map(plain) };
writeFileSync('docs/fields.json', JSON.stringify({ countries, fallback }, null, 2) + '\n');

// Distinct field keys, with the countries that use each.
const keys = new Map();
for (const [code, c] of Object.entries({ ...countries, '*': fallback })) {
  for (const f of c.fields) {
    const k = keys.get(f.key) ?? { labels: new Set(), countries: [], inputModes: new Set() };
    k.labels.add(f.label);
    k.countries.push(code);
    k.inputModes.add(f.inputMode);
    keys.set(f.key, k);
  }
}

const md = [];
md.push('# Bank fields reference', '');
md.push('Generated by `scripts/export-fields.mjs`. Do not edit by hand. Full detail (patterns, help text, error messages) is in `fields.json`.', '');
md.push('## All field keys', '');
md.push('Every key a form or database column may need. `*` is the fallback layout.', '');
md.push('| Key | Label(s) | Input | Used by |', '| --- | --- | --- | --- |');
for (const [key, k] of [...keys.entries()].sort()) {
  const used = k.countries.length > 12 ? `${k.countries.length} countries` : k.countries.join(', ');
  md.push(`| \`${key}\` | ${[...k.labels].join(' / ')} | ${[...k.inputModes].join(' / ')} | ${used} |`);
}
md.push('', '## By country', '');
md.push('Field order is the order to render. "Required" means required unless one of the listed alternatives is filled.', '');
const section = (code, name, fields) => {
  md.push(`### ${name} (${code})`, '');
  md.push('| Key | Label | Placeholder | Required | Input | Max | Options |', '| --- | --- | --- | --- | --- | --- | --- |');
  for (const f of fields) {
    const req = !f.required ? 'optional' : f.requiredUnless.length ? `unless ${f.requiredUnless.join(' or ')}` : 'yes';
    const opts = f.options ? f.options.map((o) => o.value).join(', ') : '';
    md.push(`| \`${f.key}\` | ${f.label} | ${f.placeholder} | ${req} | ${f.inputMode} | ${f.maxLength} | ${opts} |`);
  }
  md.push('');
};
section('*', 'Any other country (fallback)', fallback.fields);
for (const code of codes) section(code, countries[code].name, countries[code].fields);
writeFileSync('docs/FIELDS.md', md.join('\n'));
console.log(`${codes.length} countries, ${keys.size} distinct field keys`);
